from collections import OrderedDict, defaultdict
فواتير = OrderedDict()
for d,c,q,pu,ملاحظة in البنود:
    فواتير.setdefault(d,[]).append((c,q,pu,ملاحظة))

كلي = 0.0
print('# مسودة فواتير مشروع فيلا ايلا — 2024')
for i,(d,rows) in enumerate(sorted(فواتير.items()),1):
    مجموع = sum(q*pu for _,q,pu,_ in rows)
    كلي += مجموع
    يوم,شهر,سنة = d[8:],d[5:7],d[:4]
    print('\n## %d) %s/%s/%s — %d بند · **%.3f**' % (i,يوم,شهر,سنة,len(rows),مجموع))
    print('| الصنف | كمية | إفرادي | إجمالي |')
    print('|---|--:|--:|--:|')
    for c,q,pu,ملاحظة in rows:
        اسم = m[c]['name'] + ((' *(%s)*' % ملاحظة) if ملاحظة else '')
