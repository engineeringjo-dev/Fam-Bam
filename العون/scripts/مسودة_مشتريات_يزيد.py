# ── 3) مطابقة مقترحة مع الكتالوج (اقتراح بس — بيعتمده مدير الأصناف)
def norm(s):
    s = re.sub('[أإآ]', 'ا', s).replace('ة', 'ه').replace('ى', 'ي').replace('"', '').replace('×', '*').replace('  ', ' ')
    s = re.sub(r'\b(انش|سم)\b', '', s); return ' '.join(s.split())
SZ = lambda s: set(re.findall(r'\d+(?:[./]\d+)?', s))
CN = [(norm(c['name']), c) for c in CAT]
def match(b):
    nb = norm(b); szb = SZ(nb); best = (0, None)
    for nc, c in CN:
        if nb.split()[0] not in nc: continue
        if szb and not szb <= SZ(nc): continue
        r = difflib.SequenceMatcher(None, nb, nc).ratio()
        if r > best[0]: best = (r, c)
    return best if best[0] >= 0.55 else (0, None)
